function pad(value) {
  return String(value).padStart(2, '0')
}

function makeAttendance() {
  const rows = []
  let id = 1

  for (let day = 1; day <= 31; day += 1) {
    const date = new Date(2026, 4, day)
    const weekday = date.getDay()

    if (weekday === 0 || weekday === 6) {
      continue
    }

    employees.forEach((employee, employeeIndex) => {
      const pattern = (day + employeeIndex) % 11
      const status = pattern === 0 ? 'absent' : pattern === 1 ? 'late' : 'on_time'
      const checkIn = status === 'absent' ? '' : status === 'late' ? '08:27' : '08:03'
      const checkOut = status === 'absent' ? '' : pattern === 2 ? '17:05' : '17:35'

      rows.push({
        id: id,
        employeeId: employee.id,
        date: `2026-05-${pad(day)}`,
        checkIn,
        checkOut,
        status,
      })
      id += 1
    })
  }

  return rows
}

